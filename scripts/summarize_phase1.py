"""Aggregate Phase-1 runs into results/: headline tables (CSV + markdown) and headline figures.
Reads the LATEST run of each experiment. Usage: PYTHONPATH=src nullshift-venv/bin/python scripts/summarize_phase1.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from nullshift import paths  # noqa: E402

import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from nullshift.nuisance import FAMILIES  # noqa: E402

OUT = paths.RESULTS
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)
KEY = ["raw", "geo", "geoP", "rad", "geoP+rad", "shiftV+gate", "localmin", "blur", "phasecorr", "histmatch", "rrn",
       "classic", "classic+ns"]


def latest(exp, pattern="*"):
    runs = [r for r in sorted((paths.EXPERIMENTS / exp / "runs").glob(pattern)) if (r / "metrics.json").exists()]
    return runs[-1] if runs else None


def md(df):
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join([df.index.name or ""] + cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for i, r in df.iterrows():
        lines.append("| " + " | ".join([str(i)] + [f"{v:.3f}" if isinstance(v, float) else str(v) for v in r.values]) + " |")
    return "\n".join(lines)


parts = ["# Phase-1 tables (auto-generated by scripts/summarize_phase1.py)\n"]
e03 = latest("E03_nullpair_dose", "*_dinov3L_main")
if e03:
    parts.append(f"## E03 null-pair dose-response (run `{e03.name}`)\n")
    clean = pd.read_csv(e03 / "table_clean_test.csv").set_index("method")
    cols = ["patch_F1", "patch_AUROC", "pix_F1", "patch_F1_at_R90", "FPR_real_unchanged_at_R90",
            "median_score_true_change", "median_score_real_unchanged"]
    parts.append("### Clean LEVIR test (2048 tiles), thresholds from clean val\n" + md(clean.loc[[m for m in KEY if m in clean.index], cols]) + "\n")
    null = pd.read_csv(e03 / "table_null_fcr.csv")
    for val, title in [("AUROC_change_vs_null", "AUROC(true-change vs null patches), mean over doses 1-5 (higher = better)"),
                       ("NCR", "Nuisance-to-change ratio = median null / median true-change score, mean over doses (lower = better)"),
                       ("FCR_R99", "FCR at tau_R99 (99 % recall on clean val), mean over doses (lower = better)"),
                       ("FCR_R90", "FCR at tau_R90, mean over doses"), ("FCR", "FCR at tau* (F1-optimal), mean over doses")]:
        t = null[null.family != "identity"].pivot_table(index="method", columns="family", values=val, aggfunc="mean")
        t = t.loc[[m for m in KEY if m in t.index], [f for f in FAMILIES if f in t.columns]]
        t.to_csv(OUT / f"E03_{val}.csv")
        parts.append(f"### {title}\n" + md(t) + "\n")
    for val in ["FCR_R99", "NCR", "AUROC_change_vs_null"]:
        t = null[null.dose_idx == 3].pivot_table(index="method", columns="family", values=val)
        t = t.loc[[m for m in KEY if m in t.index], [f for f in FAMILIES if f in t.columns]]
        parts.append(f"### {val} at dose index 3 (G1 1 px, G2 1 px RMS, G3 2 px, radiometric mid doses)\n" + md(t) + "\n")
    show = ["raw", "geo", "geoP", "geoP+rad", "rad", "shiftV+gate", "localmin", "phasecorr", "classic", "classic+ns"]
    fams = ["G1_shift", "G2_field", "G3_parallax", "C1_compound", "R3_haze", "R4_colour", "R5_jpeg", "R7_blur"]
    for val, yl in [("NCR", "median null / median true-change score"), ("FCR_R99", "FCR @ tau_R99"),
                    ("AUROC_change_vs_null", "AUROC change vs null")]:
        fig, axs = plt.subplots(2, 4, figsize=(19, 8.5))
        for ax, fam in zip(axs.ravel(), fams):
            s = null[null.family == fam]
            for m in show:
                t = s[s.method == m].sort_values("dose_idx")
                ax.plot(t.dose_idx, t[val], marker="o", ms=3, label=m,
                        lw=2.8 if m in ("geoP", "geoP+rad", "classic+ns") else 1.1,
                        ls="-" if m in ("raw", "geo", "geoP", "geoP+rad", "rad", "classic+ns") else "--")
            ax.set_title(f"{fam} ({FAMILIES[fam]['unit'][:40]})", fontsize=9)
            ax.set_xticks(range(1, 6)); ax.set_xticklabels([str(FAMILIES[fam]["doses"][i]) for i in range(1, 6)])
            ax.grid(alpha=.3); ax.set_ylabel(yl, fontsize=8)
        axs.ravel()[0].legend(fontsize=7, ncol=2)
        fig.suptitle(f"NullShift Phase 1 - null pairs, LEVIR-CD test512, DINOv3-L/16 SAT: {yl}")
        fig.savefig(FIG / f"headline_{val}.png", dpi=110, bbox_inches="tight")
        plt.close(fig)

e04 = latest("E04_perturbed_pair", "*_dinov3L_main")
if e04:
    parts.append(f"## E04 perturbed real pairs (run `{e04.name}`)\n")
    tab = pd.read_csv(e04 / "table_perturbed.csv")
    base = tab[tab.family == "clean"].set_index("method")[["patch_F1", "patch_AUROC"]]
    for val in ["dF1_patch", "dAUROC_patch"]:
        t = tab[tab.family != "clean"].pivot_table(index="method", columns="family", values=val, aggfunc="mean")
        t = t.loc[[m for m in KEY if m in t.index], [f for f in FAMILIES if f in t.columns]]
        t["mean"] = t.mean(1)
        t = t.join(base.rename(columns=lambda c: "clean512_" + c))
        t.to_csv(OUT / f"E04_{val}.csv")
        parts.append(f"### {val}: change vs the same tiles clean (mean over doses 1, 3, 5)\n" + md(t) + "\n")

e02 = latest("E02_selectivity", "*_dinov3L_test512")
if e02:
    parts.append(f"## E02 energy selectivity (run `{e02.name}`)\n")
    tab = pd.read_csv(e02 / "table_energy.csv")
    ops = ["geo", "geo4", "geoP", "geo-smooth", "shiftV", "shiftV+gate", "rad", "rad+gate", "geo+rad", "geoP+rad"]
    pv = tab[tab.dose_idx.isin([0, 3])].pivot_table(index="set", columns="operator", values="removed_frac")
    pv = pv[[o for o in ops if o in pv.columns]]
    pv.to_csv(OUT / "E02_removed_frac_dose3.csv")
    parts.append("### Fraction of residual energy removed (null pairs at dose idx 3; real pairs)\n" + md(pv) + "\n")
    g = pd.read_csv(e02 / "table_gate_phi.csv")
    gp = g[g.dose_idx.isin([0, 3])].pivot_table(index="set", columns="what", values="mean")
    parts.append("### NFAD incidence gate: mean gamma and spatial participation ratio phi\n" + md(gp) + "\n")

(OUT / "PHASE1_TABLES.md").write_text("\n".join(parts))
print("\n".join(parts))
